"""Run the law-QA experiments end to end, one after another (the GPU runs one job at a time).

Stages
  control   the already trained control run (training/configs/law-qa-lora.yaml):
            pick best checkpoint, test loss, and the four systems Base / LoRA / RAG / LoRA+RAG
  series    one-variable hyper-parameter series derived from the control config:
            learning rate, LoRA rank, number of LoRA layers

Every run writes into training/results/law-qa/. Nothing is overwritten except a run's own files.

Usage (from the project root, inside backend/.venv):
    HF_HUB_OFFLINE=1 python training/run_experiments.py control
    HF_HUB_OFFLINE=1 python training/run_experiments.py series
"""
import copy
import json
import re
import subprocess
import sys
import time
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "training/results/law-qa"
CONTROL = ROOT / "training/configs/law-qa-lora.yaml"
SERIES_DIR = ROOT / "training/configs/series"
PY = sys.executable

# One independent variable per run; everything else stays as in the control config.
SERIES = {
    "lr-5e-6": {"learning_rate": 5.0e-6},
    "lr-2e-5": {"learning_rate": 2.0e-5},
    "rank-4": {"lora_parameters": {"rank": 4}},
    "rank-16": {"lora_parameters": {"rank": 16}},
    "layers-8": {"num_layers": 8},
}


def run(cmd: list[str], log: Path | None = None) -> str:
    print("$", " ".join(cmd), flush=True)
    start = time.time()
    proc = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    output = proc.stdout + proc.stderr
    if log:
        log.write_text(output)
    if proc.returncode != 0:
        print(output[-3000:])
        raise SystemExit(f"command failed ({proc.returncode})")
    print(f"  done in {time.time() - start:.0f}s", flush=True)
    return output


def test_loss(adapter: str, label: str) -> dict:
    out = run(
        ["mlx_lm.lora", "--model", "models/Llama-3.2-1B-Instruct-4bit", "--data", "data/law-qa",
         "--test", "--test-batches", "-1", "--batch-size", "4", "--mask-prompt",
         "--max-seq-length", "512", "--adapter-path", adapter, "--seed", "42"],
        RESULTS / f"test_{label}.log",
    )
    m = re.search(r"Test loss (\d+\.\d+), Test ppl (\d+\.\d+)", out)  # the line ends with a full stop
    return {"test_loss": float(m[1]), "test_ppl": float(m[2])}


def evaluate(label: str, adapter: str | None = None, rag_k: int = 0) -> dict:
    cmd = [PY, "training/evaluate.py", "--label", label]
    if adapter:
        cmd += ["--adapter", adapter]
    if rag_k:
        cmd += ["--rag-k", str(rag_k)]
    run(cmd, RESULTS / f"eval_{label}.log")
    return json.loads((RESULTS / f"summary_{label}.json").read_text())


def train(config: Path, label: str) -> float:
    start = time.time()
    run(["mlx_lm.lora", "-c", str(config)], RESULTS / f"train_{label}.log")
    return round(time.time() - start, 1)


def select_best(label: str, adapter_dir: str) -> dict:
    run([PY, "training/select_best.py", str(RESULTS / f"train_{label}.log"), adapter_dir])
    curve_file = RESULTS / f"curve_{label}.json"
    (RESULTS / "curve.json").rename(curve_file)
    return json.loads(curve_file.read_text())


def save(name: str, data: dict) -> None:
    path = RESULTS / "experiments.json"
    allres = json.loads(path.read_text()) if path.exists() else {}
    allres[name] = data
    path.write_text(json.dumps(allres, indent=2, ensure_ascii=False))


def stage_control() -> None:
    cfg = yaml.safe_load(CONTROL.read_text())
    adapter = cfg["adapter_path"]
    # The control run was started by hand and logged to train.log; keep that name for it.
    if (RESULTS / "train.log").exists() and not (RESULTS / "train_control.log").exists():
        (RESULTS / "train.log").rename(RESULTS / "train_control.log")
    curve = select_best("control", adapter)
    best = curve["best"]["folder"]
    result = {"config": cfg, "curve": {"best": curve["best"], "last": curve["last"]}}
    result["test_base"] = test_loss("", "base")
    result["test_last"] = test_loss(adapter, "control_last")
    result["test_best"] = test_loss(best, "control_best")
    result["eval"] = {
        "base": evaluate("base"),
        "lora": evaluate("lora", best),
        "rag": evaluate("rag", rag_k=3),
        "lora_rag": evaluate("lora_rag", best, rag_k=3),
    }
    save("control", result)


def stage_series() -> None:
    base = yaml.safe_load(CONTROL.read_text())
    SERIES_DIR.mkdir(parents=True, exist_ok=True)
    for name, change in SERIES.items():
        cfg = copy.deepcopy(base)
        for k, v in change.items():
            cfg[k] = {**cfg[k], **v} if isinstance(v, dict) else v
        cfg["adapter_path"] = f"adapters/law-qa-{name}"
        path = SERIES_DIR / f"{name}.yaml"
        path.write_text(f"# Generated by run_experiments.py: control config + {change}\n" + yaml.safe_dump(cfg, sort_keys=False))
        seconds = train(path, name)
        curve = select_best(name, cfg["adapter_path"])
        result = {
            "change": change,
            "train_seconds": seconds,
            "curve": {"best": curve["best"], "last": curve["last"]},
            "test_best": test_loss(curve["best"]["folder"], f"{name}_best"),
            "eval": evaluate(name, curve["best"]["folder"]),
        }
        save(name, result)


if __name__ == "__main__":
    stages = {"control": stage_control, "series": stage_series}
    for stage in sys.argv[1:] or ["control", "series"]:
        stages[stage]()
